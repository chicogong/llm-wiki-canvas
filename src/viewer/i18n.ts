export type ViewerCopy = typeof UI_COPY.en | typeof UI_COPY["zh-CN"];

export function detectViewerLocale(search: string, languages: readonly string[]): ViewerLocale {
  const requested = new URLSearchParams(search).get("lang");
  if (requested === "zh" || requested === "zh-CN") return "zh-CN";
  if (requested === "en") return "en";
  return languages.some((language) => language.toLowerCase().startsWith("zh")) ? "zh-CN" : "en";
}

export function localeHref(locale: ViewerLocale): string {
  const url = new URL(location.href);
  url.searchParams.set("lang", locale === "en" ? "zh-CN" : "en");
  return `${url.pathname}${url.search}${url.hash}`;
}
